"""Qt-free presentation helpers (HTML for the insights pane, date formatting) so they can be unit-tested."""
from __future__ import annotations

import html
from datetime import datetime

from ..analysis.deadlines import NO_DEADLINE
from ..models import EmailRecord, Summary

PRIORITY_COLORS = {"High": "#d64545", "Medium": "#c98a00", "Low": "#7a8088"}


def format_list_date(dt: datetime, now: datetime | None = None) -> str:
    local = dt.astimezone()
    now = now or datetime.now().astimezone()
    if local.date() == now.date():
        return local.strftime("%H:%M")
    if local.year == now.year:
        return f"{local.day} {local.strftime('%b')}"
    return f"{local.day} {local.strftime('%b %Y')}"


def format_full_date(dt: datetime) -> str:
    return dt.astimezone().strftime("%a %d %b %Y, %H:%M")


def format_addresses(addrs) -> str:
    return ", ".join(f"{n} <{e}>" if n else e for n, e in addrs)


def _ul(items: list[str]) -> str:
    return "<ul>" + "".join(f"<li>{html.escape(i)}</li>" for i in items) + "</ul>"


def render_priority_html(rec: EmailRecord) -> str:
    e = html.escape
    overridden = rec.user_priority is not None
    color = PRIORITY_COLORS.get(rec.priority, "#7a8088")
    out = [f"<h3>Priority: <span style='color:{color}'>{e(rec.priority)}</span>"
           f"{' <small>(set by you)</small>' if overridden else ''}</h3>"]
    if overridden:
        out.append(f"<p><i>InboxPilot's automatic estimate was {e(rec.auto_priority)}.</i></p>")
    out.append("<p><b>Reasons:</b></p><ul style='list-style-type:none; margin-left:0; padding-left:0'>")
    for r in rec.priority_reasons:
        out.append(f"<li>{'&#10003;' if r.positive else '&#8226;'} {e(r.text)}</li>")
    out.append("</ul>")
    out.append("<p><small>Priority is an estimate from signals in the message, not a judgement of what matters to you. "
               "Use the Priority box above to override it.</small></p>")
    return "".join(out)


def render_followup_html(rec: EmailRecord) -> str:
    e = html.escape
    out = []
    if rec.needs_reply:
        manual = rec.user_needs_reply is True
        reason = "Marked as needing a reply by you." if manual or not rec.followup_reason else rec.followup_reason
        out.append("<h3>Needs Reply</h3>"
                   f"<p><b>From:</b> {e(rec.sender_display)}<br><b>Subject:</b> {e(rec.display_subject)}</p>"
                   f"<p><b>Reason:</b><br>{e(reason)}</p>")
        if rec.followup_evidence and not manual:
            out.append(f"<p><i>\u201c{e(rec.followup_evidence)}\u201d</i></p>")
    if rec.follow_up:
        if rec.user_follow_up:
            why = "You flagged this message for follow-up."
        elif rec.is_sent:
            why = "You sent this message and no reply has arrived yet."
            if rec.followup_evidence:
                why += f" You asked: \u201c{e(rec.followup_evidence)}\u201d"
        else:
            why = "Flagged for follow-up."
        out.append(f"<h3>Follow Up</h3><p>{why}</p>")
    return "".join(out)


def render_summary_html(s: Summary) -> str:
    e = html.escape
    deadline = s.deadline or NO_DEADLINE
    people = s.people or ["No people identified."]
    engine = ("Generated by the optional AI service from this email's text. Check it against the original."
              if s.engine == "ai" else
              "Generated on this computer from the email text (no AI service used)."
              if s.engine == "local" else f"Generated locally ({e(s.engine)}).")
    return (f"<h3>Summary</h3><p>{e(s.summary)}</p>"
            f"<h3>Key Points</h3>{_ul(s.key_points)}"
            f"<h3>Action Items</h3>{_ul(s.action_items)}"
            f"<h3>Deadline</h3><p>{e(deadline)}</p>"
            f"<h3>People Mentioned</h3>{_ul(people)}"
            f"<h3>Suggested Response</h3><p>{e(s.suggested_response)}</p>"
            f"<p><small>{engine}</small></p>")


def render_insights_html(rec: EmailRecord, summary: Summary) -> str:
    return render_priority_html(rec) + render_followup_html(rec) + "<hr>" + render_summary_html(summary)


def category_reason_text(rec: EmailRecord) -> str:
    if rec.user_category:
        return f"Category set by you (automatic suggestion: {rec.auto_category})."
    return "Suggested because: " + "; ".join(rec.category_reasons) if rec.category_reasons else ""
